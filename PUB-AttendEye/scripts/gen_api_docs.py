"""Generates docs/API.md from the live FastAPI route table (so it cannot drift from the code).
    python scripts/gen_api_docs.py
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.main import app  # noqa: E402

def all_routes():
    for r in app.routes:
        sub = getattr(r, "original_router", None)  # FastAPI wraps include_router() results lazily
        yield from (sub.routes if sub is not None else [r])


rows = []
for r in all_routes():
    if not getattr(r, "path", "").startswith("/api"):
        continue
    for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
        deps = {d.call.__name__ for d in getattr(r, "dependant").dependencies} if hasattr(r, "dependant") else set()
        auth = "admin" if "require_admin" in deps else "teacher" if "current_teacher" in deps else "public"
        doc = (r.endpoint.__doc__ or "").strip().split("\n")[0]
        rows.append((r.path, m, auth, getattr(r, "status_code", None) or 200, doc))
rows.sort()
out = ["# PUB AttendEye API", "",
       "Generated by `python scripts/gen_api_docs.py`. All state-changing calls need the header `X-Requested-With: AttendEye` "
       "and a session cookie from `POST /api/auth/login`. Errors are JSON `{\"detail\": ...}`; validation errors "
       "(422) use `{\"detail\": {\"message\", \"fields\"}}`. Face templates are never returned by any endpoint.", "",
       "| Method | Path | Access | Success | Notes |", "|---|---|---|---|---|"]
out += [f"| {m} | `{p}` | {a} | {s} | {d} |" for p, m, a, s, d in rows]
Path(__file__).resolve().parent.parent.joinpath("docs", "API.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(rows)} endpoints documented")
